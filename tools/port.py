def die(msg):
    raise SystemExit("port.py: " + msg)


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save(path, value):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(value, f, indent=2, ensure_ascii=False)
        f.write("\n")


def copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(src, dst)


def rid(name):
    """`graveyard:foo/bar` -> ('graveyard', 'foo/bar'); bare names are vanilla's."""
    if ":" in name:
        ns, path = name.split(":", 1)
    else:
        ns, path = "minecraft", name
    return ns, path


class Upstream:
    def __init__(self, root):
        self.root = root
        self.res = os.path.join(root, "common", "src", "main", "resources")
        self.neo = os.path.join(root, "neoforge", "src", "main", "resources")
