"""Build content/ (the .hmod tree) from The Graveyard's upstream sources.

Part of the Horizon port of The Graveyard by finallion (GPL-3.0-only).
Changed for Horizon by the Saison 2 server; see NOTICE.md.

    python -I tools/port.py <upstream checkout>

`<upstream checkout>` is the extracted tarball of
https://github.com/finallion/The_Graveyard at the commit named in NOTICE.md.
The script copies the GPL assets and data the port uses, unchanged, and writes
the Horizon declarations next to them:

- the blocks the kept structures place, each on a vanilla template
  (data/graveyard/horizon/block/), with their items, models, loot and recipes;
- the kept structures rewritten from upstream's `graveyard:<name>` structure
  type (TGJigsawStructure, Java) to vanilla's jigsaw, with the start rules the
  game can read under `horizon:start_checks`;
- the three ported mobs (ghoul, revenant, nightmare) as living entity types on
  the zombie template, with upstream's attributes, loot and natural spawns.

Everything under content/assets/graveyard, content/data and the generated
lists is rewritten on each run, so the result only depends on the upstream
checkout and this file.
"""
