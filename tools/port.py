UNSUPPORTED_LOOT = ("graveyard:pages_in_loot", "graveyard:chronicle/")


def known_item(name, registered):
    ns, path = rid(name)
    return ns != NS or path in registered


def clean_loot(value, registered):
    """Drops loot entries and pools that name what this port lacks: an item it
    does not register, or upstream's Chronicle pages (a Java loot condition)."""
    def bad(entry):
        text = json.dumps(entry)
        if any(u in text for u in UNSUPPORTED_LOOT):
            return True
        for m in re.finditer(r'"name": "(graveyard:[a-z0-9_/]+)"', text):
            if not known_item(m.group(1), registered):
                return True
        return False

    def walk(v):
        if isinstance(v, dict):
            out = {}
            for k, x in v.items():
                if k in ("entries", "children") and isinstance(x, list):
                    out[k] = [walk(e) for e in x if not bad(e)]
                else:
                    out[k] = walk(x)
            return out
        if isinstance(v, list):
            return [walk(x) for x in v]
        return v

    out = walk(value)
    out["pools"] = [p for p in out.get("pools", []) if p.get("entries")]
    return out


def recipe_ok(recipe, registered):
    if not recipe.get("type", "").startswith("minecraft:"):
        return False
    for m in re.finditer(r'"(graveyard:[a-z0-9_/]+)"', json.dumps(recipe)):
        if not known_item(m.group(1), registered):
            return False
    return True


