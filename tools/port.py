# Worldgen: follow the kept structures' pools to their templates.


def collect_worldgen(up):
    pools, templates, processor_lists = set(), set(), set()
    todo = []
    structures = {}
    for name in STRUCTURES:
        s = load(up.data("worldgen", "structure", name + ".json"))
        structures[name] = s
        todo.append(s["start_pool"])
    while todo:
        pool = todo.pop()
        ns, path = rid(pool)
        if ns != NS or pool in pools:
            continue
        file = up.data("worldgen", "template_pool", path + ".json")
        if not os.path.exists(file):
            die(f"pool {pool} is missing upstream")
        pools.add(pool)
        p = load(file)
        if p.get("fallback"):
            todo.append(p["fallback"])
        for el in p.get("elements", []):
            e = el["element"]
            for key in ("location",):
                if key in e:
                    tns, tpath = rid(e[key])
                    if tns == NS and tpath not in templates:
                        templates.add(tpath)
                        todo.extend(jigsaw_pools(up, tpath))
            procs = e.get("processors")
            if isinstance(procs, str) and rid(procs)[0] == NS:
                processor_lists.add(rid(procs)[1])
            elif isinstance(procs, dict) and procs.get("processors"):
                die(f"inline processors in {pool}")
    return structures, pools, templates, processor_lists


def jigsaw_pools(up, template):
    root = nbtlib.read(up.data("structure", template + ".nbt"))
    out = []
    for b in root.get("blocks", []):
        nbt = b.get("nbt")
        if nbt and nbt.get("id") == "minecraft:jigsaw" and nbt.get("pool"):
            out.append(nbt["pool"])
    return out


def palette_states(up, templates):
    """{block id: {property: set(values)}} for every graveyard block placed."""
    props = {}
    for t in sorted(templates):
        root = nbtlib.read(up.data("structure", t + ".nbt"))
        for palette in nbtlib.palettes(root):
            for s in palette:
                name = s.get("id") or s.get("Name")
                if not name.startswith(NS + ":"):
                    continue
                entry = props.setdefault(name.split(":", 1)[1], {})
                for k, v in (s.get("properties") or s.get("Properties") or {}).items():
                    entry.setdefault(k, set()).add(v)
    return props


def start_checks(s):
    """TGJigsawStructure.isTerrainFlat as `horizon:start_checks`: no water at
    the start column, and the terrain heights around within
    `max_height_difference`. Upstream samples 5 columns `terrain_check_size`
    blocks apart; the game samples chunk centres in a radius, so the radius is
    the check size in chunks (none under half a chunk)."""
    checks = {}
    if s.get("structure_name") != "haunted_house":
        checks["liquid"] = "top"
    radius = round(s.get("terrain_check_size", 0) / 16)
    if radius >= 1:
        checks["terrain_radius"] = radius
        checks["terrain_range"] = s.get("max_height_difference", 3)
    return checks


def write_worldgen(up, structures, pools, templates, processor_lists):
    for name, s in structures.items():
        out = {
            "type": "minecraft:jigsaw",
            "start_pool": s["start_pool"],
            "size": s["size"],
            "max_distance_from_center": s["max_distance_from_center"],
            "biomes": s["biomes"],
            "step": s["step"],
            "use_expansion_hack": s["use_expansion_hack"],
            "start_height": s["start_height"],
        }
        for key in ("terrain_adaptation", "project_start_to_heightmap", "start_jigsaw_name"):
            if key in s:
                out[key] = s[key]
        # findGenerationPoint's own starts (TGJigsawStructure, Java): the crypt
        # starts at a random height from -40 to -10, the lich prison 210 blocks
        # over the surface, both at a random column of the chunk.
        if name == "crypt":
            out["start_height"] = {
                "type": "minecraft:uniform",
                "min_inclusive": {"absolute": -40},
                "max_inclusive": {"absolute": -10},
            }
        elif name == "lich_prison":
            out["start_height"] = {"absolute": 210}
        else:
            checks = start_checks(s)
            if checks:
                out["horizon:start_checks"] = checks
        overrides = {}
        for cat, ov in s.get("spawn_overrides", {}).items():
            spawns = [x for x in ov.get("spawns", [])
                      if rid(x["type"])[0] != NS or x["type"] in MOB_IDS]
            # A category whose spawns were all upstream mobs this port lacks
            # is left to the biome's own spawns rather than emptied.
            if spawns:
                overrides[cat] = dict(ov, spawns=spawns)
        out["spawn_overrides"] = overrides
        save(out_data("worldgen", "structure", name + ".json"), out)

    for name in STRUCTURES:
        src = up.data("worldgen", "structure_set", name + "_structure.json")
        save(out_data("worldgen", "structure_set", name + "_structure.json"), load(src))

    for pool in pools:
        path = rid(pool)[1]
        save(out_data("worldgen", "template_pool", path + ".json"),
             load(up.data("worldgen", "template_pool", path + ".json")))

    # Upstream's three processor lists hold one Java processor each. In
    # 4.0.0 RemoveWaterlogged(Crypt)Processor return every block unchanged,
    # and SwitchSpawnerProcessor only acts when the disableWitherSkeletonSpawner
    # config flag is set (off by default): all three are empty lists here.
    for name in processor_lists:
        save(out_data("worldgen", "processor_list", name + ".json"), {"processors": []})

    for t in templates:
        copy(up.data("structure", t + ".nbt"), out_data("structure", t + ".nbt"))

    tagdir = up.data("tags", "worldgen", "biome")
    for name, s in structures.items():
        tag = s["biomes"]
        if tag.startswith("#" + NS + ":"):
            path = tag[len(NS) + 2:]
            save(out_data("tags", "worldgen", "biome", path + ".json"),
                 load(os.path.join(tagdir, path + ".json")))
    for mob in MOBS:
        save(out_data("tags", "worldgen", "biome", mob + "_spawns.json"),
             load(os.path.join(tagdir, mob + "_spawns.json")))
    for tag, values in CONVENTION_BIOMES.items():
        save(os.path.join(CONTENT, "data", "c", "tags", "worldgen", "biome", tag + ".json"),
             {"replace": False, "values": values})


