def main():
    if len(sys.argv) != 2:
        die("usage: python -I tools/port.py <upstream checkout>")
    up = Upstream(sys.argv[1])

    for d in (os.path.join(CONTENT, "assets"), os.path.join(CONTENT, "data")):
        if os.path.isdir(d):
            shutil.rmtree(d)

    structures, pools, templates, processor_lists = collect_worldgen(up)
    write_worldgen(up, structures, pools, templates, processor_lists)
    used = palette_states(up, templates)
    print(f"{len(structures)} structures, {len(pools)} pools, {len(templates)} templates, "
          f"{len(used)} graveyard blocks placed")

    assets = Assets(up)
    blocks = sorted(used)
    registered = set(blocks) | set(ITEMS)
    for name in blocks:
        kind = block_kind(name)
        decl = block_declaration(name, kind, used[name])
        # A block upstream gives no item (the lore book: found, not crafted).
        if not os.path.exists(up.assets("items", name + ".json")):
            decl["item"] = False
        save(out_data("horizon", "block", name + ".json"), decl)
        assets.blockstate(name)
        if decl["item"]:
            assets.item(name)
    for name, decl in ITEMS.items():
        save(out_data("horizon", "item", name + ".json"), decl)
        assets.item(name)

    # The creative tab: upstream's items this port has, blocks first.
    save(out_data("horizon", "creative_tab", "graveyard.json"),
         {"title": "itemGroup.graveyard.group",
          "icon": f"{NS}:gravestone" if "gravestone" in registered else f"{NS}:{blocks[0]}",
          "items": [f"{NS}:{n}" for n in blocks
                    if os.path.exists(up.assets("items", n + ".json"))]
                   + [f"{NS}:{n}" for n in ITEMS]})

    # Atlas additions (two vanilla item sprites upstream's models reuse).
    atlases = os.path.join(up.res, "assets", "minecraft", "atlases")
    for f in os.listdir(atlases):
        copy(os.path.join(atlases, f), os.path.join(CONTENT, "assets", "minecraft", "atlases", f))

    # Loot: block drops, the chests the kept structures fill, the mobs.
    loot = up.data("loot_table")
    for name in blocks:
        src = os.path.join(loot, "blocks", name + ".json")
        if os.path.exists(src):
            save(out_data("loot_table", "blocks", name + ".json"), clean_loot(load(src), registered))
    chests = set()
    for t in templates:
        root = nbtlib.read(up.data("structure", t + ".nbt"))
        for b in root.get("blocks", []):
            table = (b.get("nbt") or {}).get("LootTable")
            if table and table.startswith(NS + ":"):
                chests.add(table.split(":", 1)[1])
    for t in sorted(chests):
        src = os.path.join(loot, t + ".json")
        if os.path.exists(src):
            save(out_data("loot_table", t + ".json"), clean_loot(load(src), registered))
        else:
            print(f"  warning: loot table {t} missing upstream")
    for mob in MOBS:
        save(out_data("loot_table", "entities", mob + ".json"),
             clean_loot(load(os.path.join(loot, "entities", mob + ".json")), registered))

    # Recipes in vanilla's types whose items all exist here.
    kept = 0
    for f in sorted(os.listdir(up.data("recipe"))):
        r = load(up.data("recipe", f))
        if recipe_ok(r, registered):
            save(out_data("recipe", f), r)
            kept += 1
    print(f"{kept} recipes kept, {len(chests)} chest loot tables")

    # Block and item tags, vanilla's and the mod's, cut to what exists.
    for base, ns in ((os.path.join(up.res, "data", "minecraft", "tags"), "minecraft"),
                     (up.data("tags"), NS)):
        for kind in ("block", "item"):
            d = os.path.join(base, kind)
            if not os.path.isdir(d):
                continue
            for dirpath, _, files in os.walk(d):
                for f in files:
                    src = os.path.join(dirpath, f)
                    tag = load(src)
                    values = []
                    for v in tag.get("values", []):
                        vid = v["id"] if isinstance(v, dict) else v
                        if vid.startswith("#") or known_item(vid, registered):
                            values.append(v)
                    if values:
                        rel = os.path.relpath(src, base)
                        save(os.path.join(CONTENT, "data", ns, "tags", rel), dict(tag, values=values))

    # Entity types (zombie template), their tags and natural spawns.
    for mob, spec in MOBS.items():
        save(out_data("horizon", "entity_type", mob + ".json"),
             {"template": "minecraft:zombie", "attributes": spec["attributes"]})
    for tag in ("undead",):
        src = os.path.join(up.res, "data", "minecraft", "tags", "entity_type", tag + ".json")
        t = load(src)
        values = [v for v in t["values"] if v in MOB_IDS]
        save(os.path.join(CONTENT, "data", "minecraft", "tags", "entity_type", tag + ".json"),
             dict(t, values=values))
    # Upstream's ghoul and revenant are zombies to the game's rules
    # (#minecraft:zombies: smite, the "zombie" checks of other mobs).
    save(os.path.join(CONTENT, "data", "minecraft", "tags", "entity_type", "zombies.json"),
         {"replace": False, "values": [f"{NS}:ghoul", f"{NS}:revenant"]})
    for mob, spec in MOBS.items():
        weight, lo, hi = spec["spawn"]
        # Upstream's `graveyard:config_spawns` modifier reads these from its
        # config; written here as NeoForge's add_spawns with the defaults.
        save(out_data("neoforge", "biome_modifier", f"add_{mob}_spawns.json"),
             {"type": "neoforge:add_spawns", "biomes": f"#{NS}:{mob}_spawns",
              "spawners": {"type": f"{NS}:{mob}", "weight": weight,
                           "minCount": lo, "maxCount": hi}})

    # Lang, sounds (the three mobs' events), entity textures.
    for f in os.listdir(up.assets("lang")):
        copy(up.assets("lang", f), out_assets("lang", f))
    sounds = load(up.assets("sounds.json"))
    keep = {k: v for k, v in sounds.items()
            if any(k.startswith(f"entity.{m}.") for m in MOBS)}
    save(out_assets("sounds.json"), keep)
    for event in keep.values():
        for s in event["sounds"]:
            name = s["name"] if isinstance(s, dict) else s
            ns, path = rid(name)
            if ns == NS:
                copy(up.assets("sounds", path + ".ogg"), out_assets("sounds", path + ".ogg"))
    for f in os.listdir(up.assets("textures", "entity")):
        if re.match(r"(ghoul_(eyes_)?skin\d|revenant(_eyes)?|nightmare)\.png$", f):
            copy(up.assets("textures", "entity", f), out_assets("textures", "entity", f))

    print(f"{len(blocks)} blocks, {len(ITEMS)} items, {len(assets.models)} models, "
          f"{len(assets.textures)} textures")
    with open(os.path.join(ROOT, "tools", "blocks.txt"), "w", encoding="utf-8", newline="\n") as f:
        for name in blocks:
            f.write(f"{name}\t{block_kind(name)}\n")


if __name__ == "__main__":
    main()
