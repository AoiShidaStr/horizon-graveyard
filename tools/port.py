# upstream name pattern -> (strength, resistance, sounds, collision, light)
def block_kind(name):
    if name.startswith("tg_"):
        return "twin"
    if name in ("dark_iron_bars", "dark_iron_door", "dark_iron_trapdoor", "dark_iron_block"):
        return "iron"
    if name.endswith("gravestone"):
        return "gravestone"
    if name.endswith("_urn"):
        return "urn"
    if name.endswith("_coffin") or name == "sarcophagus":
        return "coffin"
    if name in ("fire_brazier", "soul_fire_brazier"):
        return "brazier"
    if name.startswith("altar"):
        return "altar"
    if name in ("candle_holder", "vase_block", "lore_book", "ossuary", "pedestal"):
        return name
    return "bones"


