def block_declaration(name, kind, used):
    if kind == "twin":
        return {"template": "minecraft:" + name[3:], "item": True}
    if kind == "iron":
        hardness = 1.0 if name == "dark_iron_bars" else 5.0
        decl = {"template": IRON_TWIN[name], "item": True,
                "properties": {"hardness": hardness,
                               "explosion_resistance": 6.0 if name == "dark_iron_block" else hardness,
                               "sounds": "minecraft:iron_block"}}
        return decl
    if kind == "altar":
        # Unbreakable (strength -1, 3600000) for the altar itself; 50 / 1200 for
        # its frame (TGBlocks). No loot (noLootTable).
        decl = {"template": "minecraft:stone", "item": True,
                "properties": {"hardness": -1.0 if name == "altar" else 50.0,
                               "explosion_resistance": 3600000.0 if name == "altar" else 1200.0,
                               "sounds": "minecraft:deepslate"}}
        props = {}
        if name == "altar":
            props["bloody"] = {"type": "boolean"}
        elif name in ("altar_side", "altar_corner"):
            props["facing"] = {"type": "enum", "values": PROP_VALUES["facing"]}
        if props:
            decl["state_properties"] = props
        return decl

    hardness, resistance, sounds = KIND_PROPS_STRENGTH[kind]
    # noOcclusion() upstream: `occludes: false` (in `properties` at the pinned
    # Horizon revision).
    decl = {"template": DECOR_TEMPLATE, "item": True,
            "properties": {"hardness": hardness, "explosion_resistance": resistance,
                           "sounds": sounds, "occludes": False}}
    props = {}
    for p in KIND_PROPS[kind]:
        if p in BOOLEAN:
            props[p] = {"type": "boolean"}
        else:
            props[p] = {"type": "enum", "values": PROP_VALUES[p]}
    for p in used:
        if p != "waterlogged" and p not in props and p not in ("lit",):
            die(f"{name}: palette property {p} not declared")
    if props:
        decl["state_properties"] = props
        default = {}
        if "facing" in props:
            default["facing"] = "north"
        if "bottom" in props:
            default["bottom"] = "true"
        if "part" in props:
            default["part"] = "foot"
        if "candles" in props:
            default["candles"] = "1"
        if "rotation" in props:
            default["rotation"] = "0"
        if "variant" in props:
            default["variant"] = "closed"
        if default:
            decl["default_state"] = default
    if kind == "urn":
        decl["shapes"] = {"default": SMALL_URN if name.startswith("small_") else LARGE_URN}
    elif kind in SHAPES:
        decl["shapes"] = SHAPES[kind]
    if kind in NO_COLLISION:
        decl["collision_shapes"] = {"default": []}
    if kind == "brazier":
        # BrazierBlock.STATE_TO_LUMINANCE: 11 when lit.
        decl["state_light"] = {"property": "lit", "values": {"false": 0, "true": 11}}
    if kind == "coffin" and name != "sarcophagus":
        decl["properties"]["sounds"] = "minecraft:oak_planks"
    if kind == "coffin" and name == "sarcophagus":
        decl["properties"].update({"hardness": 1.5, "explosion_resistance": 1.5,
                                   "sounds": "minecraft:stone"})
    return decl


def model_refs(model):
    out = set()
    if isinstance(model, dict):
        for k, v in model.items():
            if k == "model" and isinstance(v, str):
                out.add(v)
            else:
                out |= model_refs(v)
    elif isinstance(model, list):
        for v in model:
            out |= model_refs(v)
    return out


class Assets:
    """Copies blockstates, item definitions, models and the textures they use."""

    def __init__(self, up):
        self.up = up
        self.models = set()
        self.textures = set()

    def model(self, ref):
        ns, path = rid(ref)
        if ns != NS or ref in self.models:
            return
        src = self.up.assets("models", path + ".json")
        if not os.path.exists(src):
            print(f"  warning: model {ref} missing upstream")
            return
        self.models.add(ref)
        m = load(src)
        copy(src, out_assets("models", path + ".json"))
        if "parent" in m:
            self.model(m["parent"])
        for tex in m.get("textures", {}).values():
            if isinstance(tex, str) and not tex.startswith("#"):
                self.texture(tex)

    def texture(self, ref):
        ns, path = rid(ref)
        if ns != NS or ref in self.textures:
            return
        src = self.up.assets("textures", path + ".png")
        if not os.path.exists(src):
            print(f"  warning: texture {ref} missing upstream")
            return
        self.textures.add(ref)
        copy(src, out_assets("textures", path + ".png"))
        meta = src + ".mcmeta"
        if os.path.exists(meta):
            copy(meta, out_assets("textures", path + ".png.mcmeta"))

    def blockstate(self, name):
        src = self.up.assets("blockstates", name + ".json")
        if not os.path.exists(src):
            print(f"  warning: no blockstate for {name}")
            return
        copy(src, out_assets("blockstates", name + ".json"))
        for ref in model_refs(load(src)):
            self.model(ref)

    def item(self, name):
        src = self.up.assets("items", name + ".json")
        if not os.path.exists(src):
            print(f"  warning: no item definition for {name}")
            return
        copy(src, out_assets("items", name + ".json"))
        for ref in model_refs(load(src)):
            self.model(ref)


